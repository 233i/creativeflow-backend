  const path = `/api/v1/admin/workflow-apis/${draft.id}`;
  await user.request(path, "GET", undefined, 401);
  await user.request(`/api/v1/workflows/${draft.id}`, "GET", undefined, 403);
  const upload = () => {
    const form = new FormData();
    form.set("file", new Blob([readFileSync(`${process.env.CREATIVEFLOW_MAF_TEST_ROOT}/data/fixture.png`)], { type: "image/png" }), "fixture.png");
    return form;
  };
  const image = await manager.request(`${path}/assets`, "POST", upload());
  const graph = { nodes: [node("input", "image", { assetUrl: image.url }), node("output", "imageOutput")],
    edges: [edge("input", "image", "output", "image")],
    externalApi: { schemaVersion: 1, inputs: [{ key: "image", label: "Image", type: "image", required: true, target: { nodeId: "input", field: "assetUrl" } }],
      outputs: [{ key: "result", label: "Result", type: "image", nodeId: "output" }] } };
  await manager.request(path, "PUT", { graph });
  const debug = await manager.request(`${path}/runs`, "POST", {}, 202);
  assert.equal((await until(() => manager.request(`${path}/runs/${debug.id}`), value => value.status === "succeeded")).status, "succeeded");
  const deployment = await manager.request(`${path}/publish`, "POST", { description: "Synthetic image passthrough", maxConcurrency: 1 });
