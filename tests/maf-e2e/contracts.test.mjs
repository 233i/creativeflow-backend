  const outputs = result.nodes.find(value => value.nodeId === "generate").output.images;
  const referenceIds = videoSubmit.body.metadata.content.map(item => new URL(item.image_url.url).pathname.split("/").at(-1));
  assert.deepEqual(referenceIds, outputs.map(item => new URL(item, origin).pathname.split("/").at(-1).replaceAll("-", "")).reverse());
