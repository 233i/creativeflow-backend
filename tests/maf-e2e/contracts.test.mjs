test("published templates instantiate independent legacy graphs without changing unknown fields", async () => {
  const graph = { nodes: [node("text", "text", { text: "template golden", preservedUnknownField: [false, 0, null] }), node("generate", "imageGenerate"), node("out", "imageOutput")],
    edges: [edge("text", "text", "generate", "prompt"), edge("generate", "image", "out", "image")], viewport: { x: 7, y: 11, zoom: 0.8 } };
  const template = await manager.request("/api/v1/admin/workflow-templates", "POST", { name: "MAF template golden", description: "Synthetic legacy template", category: "Migration", schemaVersion: 1, graph }, 201);
  await user.request(`/api/v1/workflow-templates/${template.id}`, "GET", undefined, 404);
  await manager.request(`/api/v1/admin/workflow-templates/${template.id}/publish`, "POST", {});
  const published = await user.request(`/api/v1/workflow-templates/${template.id}`);
  assert.deepEqual(published.graph, graph);
  const instance = await user.request(`/api/v1/workflow-templates/${template.id}/instantiate`, "POST", { name: "Golden instance" }, 201);
  assert.deepEqual(instance.graph, graph);
  const result = await runWorkflow(user, instance);
  assert.equal(result.status, "succeeded", result.error);
  assert.deepEqual(result.nodes.find(item => item.nodeId === "text").output.texts, ["template golden"]);
  assert.equal(result.nodes.find(item => item.nodeId === "out").output.images.length, 1);
  await user.request(`/api/v1/workflows/${instance.id}`, "PUT", { graph: { nodes: [], edges: [] } });
  assert.deepEqual((await user.request(`/api/v1/workflow-templates/${template.id}`)).graph, graph);
});
