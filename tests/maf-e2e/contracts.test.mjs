  assert.ok(result.nodes.every(value => value.status === "succeeded"));
  const before = await fixtureCalls();
  const videoSubmit = before.filter(call => call.method === "POST" && call.path === "/v1/videos").at(-1);
  assert.equal(videoSubmit.body.seconds, "15");
