using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CreativeFlow.CodeQuality;

/// <summary>基于 C# 语法树枚举手写声明，同时覆盖私有方法及位置记录自动生成的属性。</summary>
public static class SourceInventory
{
    /// <summary>扫描生产代码、测试和仓内工具，跳过编译产物及显式自动生成文件。</summary>
    public static IEnumerable<SourceMember> Read(string root)
    {
        foreach (var folder in new[] { "src", "tests", "tools" })
        {
            var directory = Path.Combine(root, folder);
            if (!Directory.Exists(directory)) continue;
            foreach (var file in Directory.EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories)
                .Where(file => !file.Split(Path.DirectorySeparatorChar).Any(part => part is "bin" or "obj"))
                .Order(StringComparer.Ordinal))
            {
                var source = File.ReadAllText(file);
                if (source.TrimStart().StartsWith("// <auto-generated", StringComparison.Ordinal)) continue;
                var tree = CSharpSyntaxTree.ParseText(
                    source, new CSharpParseOptions(LanguageVersion.CSharp14, DocumentationMode.Parse));
                foreach (var node in tree.GetRoot().DescendantNodes())
                {
                    if (Describe(node, tree, Path.GetRelativePath(root, file)) is { } member)
                        yield return member;
                }
            }
        }
    }

    /// <summary>将实际声明转换为盘点项，不把自动属性访问器或匿名函数当作手写方法。</summary>
    private static SourceMember? Describe(SyntaxNode node, SyntaxTree tree, string file)
    {
        var (kind, name, type) = node switch
        {
            MethodDeclarationSyntax method => ("method", method.Identifier.Text, method.ReturnType.ToString()),
            ConstructorDeclarationSyntax constructor => ("constructor", constructor.Identifier.Text, ""),
            DestructorDeclarationSyntax destructor => ("destructor", destructor.Identifier.Text, ""),
            OperatorDeclarationSyntax operation => ("operator", operation.OperatorToken.Text, operation.ReturnType.ToString()),
            ConversionOperatorDeclarationSyntax conversion => ("operator", conversion.Type.ToString(), conversion.Type.ToString()),
            LocalFunctionStatementSyntax function => ("local_function", function.Identifier.Text, function.ReturnType.ToString()),
            PropertyDeclarationSyntax property => ("property", property.Identifier.Text, property.Type.ToString()),
            FieldDeclarationSyntax field => ("field", string.Join(",", field.Declaration.Variables.Select(v => v.Identifier.Text)),
                field.Declaration.Type.ToString()),
            EnumMemberDeclarationSyntax value => ("enum_member", value.Identifier.Text, ""),
            ParameterSyntax parameter when parameter.Parent?.Parent is RecordDeclarationSyntax =>
                ("record_parameter", parameter.Identifier.Text, parameter.Type?.ToString() ?? ""),
            TypeDeclarationSyntax declaration when declaration is not RecordDeclarationSyntax
                && declaration.ParameterList is not null => ("primary_constructor", declaration.Identifier.Text, ""),
            _ => ("", "", ""),
        };
        if (kind.Length == 0) return null;
        var owner = node.AncestorsAndSelf().OfType<BaseTypeDeclarationSyntax>().FirstOrDefault();
        var body = node switch
        {
            BaseMethodDeclarationSyntax method => method.Body,
            LocalFunctionStatementSyntax function => function.Body,
            _ => null,
        };
        var documented = HasDocumentation(node);
        var parentStart = node.SpanStart;
        if (kind == "record_parameter")
        {
            // 位置记录的字段说明属于记录类型上的 param，不能只检查参数前一行。
            var record = node.Parent!.Parent!;
            parentStart = record.SpanStart;
            documented |= HasParameterDocumentation(record, name);
        }
        if (kind == "local_function")
        {
            // C# 不为局部函数导出 XML 文档，允许它使用普通说明注释。
            documented |= node.GetLeadingTrivia().Any(IsExplanation);
        }
        var needsLogic = body is not null && tree.GetLineSpan(body.Span).EndLinePosition.Line
            - tree.GetLineSpan(body.Span).StartLinePosition.Line >= 30
            && body.DescendantNodes().Any(child => child is IfStatementSyntax or SwitchStatementSyntax
                or ForEachStatementSyntax or ForStatementSyntax or WhileStatementSyntax or TryStatementSyntax)
            && !body.DescendantTrivia().Any(IsExplanation);
        var signature = node.ToString();
        return new SourceMember(
            file, tree.GetLineSpan(node.Span).StartLinePosition.Line + 1, node.SpanStart, parentStart,
            kind, name, owner?.Identifier.Text ?? "Program", type,
            owner?.BaseList?.Types.Select(baseType => baseType.Type.ToString()).ToArray() ?? [],
            owner is InterfaceDeclarationSyntax, documented, needsLogic, body?.OpenBraceToken.Span.End,
            signature[..Math.Min(signature.Length, 600)]);
    }

    /// <summary>要求声明具有可阅读的 XML 摘要正文，继承标记或空白标签不能代替实际说明。</summary>
    private static bool HasDocumentation(SyntaxNode node)
    {
        var documentation = node.GetLeadingTrivia()
            .Select(trivia => trivia.GetStructure()).OfType<DocumentationCommentTriviaSyntax>();
        foreach (var comment in documentation)
        {
            foreach (var element in comment.DescendantNodes().OfType<XmlElementSyntax>())
            {
                if (element.StartTag.Name.LocalName.Text == "summary"
                    && element.DescendantNodes().OfType<XmlTextSyntax>()
                        .SelectMany(text => text.TextTokens)
                        .Any(token => !string.IsNullOrWhiteSpace(token.ValueText))) return true;
            }
        }
        return false;
    }

    /// <summary>只接受对应名称的非空 param，避免把正文中的参数引用误算为字段说明。</summary>
    private static bool HasParameterDocumentation(SyntaxNode record, string name)
    {
        var pattern = @"<param\s+name\s*=\s*[""']" + Regex.Escape(name)
            + @"[""']\s*>(?<body>[\s\S]*?)</param>";
        var match = Regex.Match(record.GetLeadingTrivia().ToFullString(), pattern);
        return match.Success && !string.IsNullOrWhiteSpace(match.Groups["body"].Value.Replace("///", ""));
    }

    /// <summary>限定为方法体中的普通说明注释，不将外层 XML 摘要视为内部逻辑注释。</summary>
    private static bool IsExplanation(SyntaxTrivia trivia) =>
        trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia);
}
